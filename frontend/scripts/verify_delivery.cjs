const fs = require('node:fs')
const assert = require('node:assert/strict')
const { chromium } = require('playwright')

;(async () => {
  const credentials = JSON.parse(fs.readFileSync(process.env.PRESENTATION_CREDENTIALS_FILE, 'utf8'))
  const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true })
  const steps = [], errors = []
  try {
    const page = await browser.newPage()
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:55173/login')
    await page.locator('#username').fill(credentials.username)
    await page.locator('#password').fill(credentials.password)
    await page.getByRole('button', { name: 'Sign In', exact: true }).click()
    await page.waitForURL('**/dashboard')
    steps.push('Inicio de sesión real por formulario')
    await page.getByRole('button', { name: 'Buscar empresas y consultar fichas' }).click()
    await page.getByText('Microsoft', { exact: true }).waitFor()
    await page.getByText('Página 1 · 503 empresas', { exact: true }).waitFor()
    const logo = page.getByRole('img', { name: 'Logo de Microsoft', exact: true })
    assert(await logo.evaluate(element => element.complete && element.naturalWidth > 0))
    steps.push('Catálogo paginado de 503 símbolos y logo local de Microsoft')
    await page.getByRole('button', { name: 'Siguiente', exact: true }).click()
    await page.getByText('Página 2 · 503 empresas', { exact: true }).waitFor()
    steps.push('Segunda página accesible')
    await page.locator('#sector-filter').selectOption('healthcare')
    await page.getByRole('button', { name: 'Limpiar filtros', exact: true }).waitFor()
    await page.waitForFunction(() => [...document.querySelectorAll('.company-sector')].every(e => e.classList.contains('sector-healthcare')))
    await page.locator('#ordering-filter').selectOption('market_cap')
    await page.getByText('Orden: ↑ Menor a mayor', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Limpiar filtros', exact: true }).click()
    steps.push('Filtro por sector, cambio de orden y limpieza')
    const search = page.getByRole('combobox', { name: 'Buscar empresas', exact: true })
    await search.fill('MSFT')
    await page.getByRole('option').filter({ hasText: 'MSFT' }).waitFor()
    await search.press('ArrowDown')
    await search.press('Enter')
    await page.getByRole('button', { name: 'Eliminar MSFT', exact: true }).waitFor()
    await page.getByText('Página 1 · 1 empresas', { exact: true }).waitFor()
    steps.push('Autocompletado por teclado y persistencia del historial')
    await page.getByRole('button', { name: 'Eliminar MSFT', exact: true }).click()
    await page.getByText('No hay búsquedas recientes.', { exact: true }).waitFor()
    steps.push('Borrado individual del historial')
    await page.getByText('Microsoft', { exact: true }).click()
    await page.waitForURL('**/company/MSFT')
    await page.getByText('Fecha: 2024-06-30', { exact: false }).waitFor()
    await page.getByRole('button', { name: '5Y', exact: true }).waitFor()
    await page.locator('.recharts-pie .recharts-sector').first().waitFor({ state: 'visible' })
    const initialResponse = page.waitForResponse(r => r.url().includes('/history/?range=5Y') && r.ok())
    const started = performance.now()
    await page.getByRole('button', { name: '5Y', exact: true }).click()
    const history = await (await initialResponse).json()
    assert.equal(history.is_demo, false)
    assert(history.count > 1000)
    await page.locator('.highcharts-series path.highcharts-graph').first().waitFor({ state: 'visible' })
    const elapsed = performance.now() - started
    assert(elapsed < 2000)
    steps.push('Ficha real con fuente/fecha, cinco métricas, Altman-Z y gráfico de más de 1000 precios')
    for (const range of ['1M', '6M', '1Y']) {
      const pending = page.waitForResponse(r => r.url().includes(`/history/?range=${range}`) && r.ok())
      await page.getByRole('button', { name: range, exact: true }).click()
      assert((await (await pending).json()).count > 0)
    }
    steps.push('Los cuatro rangos de precios responden con datos persistidos')
    await page.evaluate(() => localStorage.setItem('access_token', 'invalid-access-for-refresh-test'))
    const refreshed = page.waitForResponse(r => r.url().includes('/auth/refresh/') && r.ok())
    await page.reload()
    await refreshed
    await page.getByText('Microsoft', { exact: true }).waitFor()
    steps.push('Renovación real de sesión y reintento de la petición protegida')
    await page.goto('http://127.0.0.1:55173/dashboard')
    await page.getByRole('button', { name: 'Cerrar Sesión', exact: true }).click()
    await page.waitForURL('**/login')
    assert.equal(await page.evaluate(() => localStorage.getItem('access_token')), null)
    steps.push('Cierre de sesión y limpieza local')
    assert.deepEqual(errors, [])
    const report = { recorded_at: new Date().toISOString(), passed: true, steps, page_errors: errors,
      chart_points: history.count, chart_elapsed_ms: Number(elapsed.toFixed(2)), chart_budget_ms: 2000,
      chart_budget_source: 'Presupuesto interno del proyecto', browser: browser.version(),
      data_scope: '503 símbolos; un balance MSFT 2024; 1254 cierres MSFT; 500 logos y tres alternativas de ticker' }
    fs.writeFileSync(process.env.DELIVERY_REPORT, JSON.stringify(report, null, 2))
    console.log(JSON.stringify(report))
  } finally { await browser.close() }
})().catch(error => { console.error(error.stack); process.exitCode = 1 })
