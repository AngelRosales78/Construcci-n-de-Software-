const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const web = 'http://127.0.0.1:55183'
const root = path.resolve(__dirname, '../../..')
const output = path.join(root, 'output/sprint2_cierre_26_oct')
const credentials = JSON.parse(fs.readFileSync(path.join(root, 'presentation_runtime_sprint2/demo_credentials.json'), 'utf8'))
fs.mkdirSync(output, { recursive: true })

;(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const steps = [], errors = []
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    page.on('pageerror', error => errors.push(error.message))
    page.setDefaultTimeout(30000)
    await page.goto(`${web}/login`)
    await page.locator('#username').fill(credentials.username)
    await page.locator('#password').fill(credentials.password)
    await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
    await page.waitForURL('**/dashboard')
    await page.goto(`${web}/company/MSFT`)
    await page.getByRole('button', { name: 'Resumen', exact: true }).waitFor()
    assert.equal(await page.locator('.simulation-panel').isVisible(), false)
    await page.screenshot({ path: path.join(output, 'resumen_escritorio.png'), fullPage: true })
    await page.getByRole('button', { name: 'Salud financiera', exact: true }).click()
    await page.locator('.overall-score-value').getByText('85,25', { exact: false }).waitFor()
    await page.screenshot({ path: path.join(output, 'salud_escritorio.png'), fullPage: true })
    steps.push('Login real y regresión de pilares, radar y puntaje FY2024')
    steps.push('Navegación en cuatro secciones; resumen inicial sin paneles técnicos desplegados')
    await page.getByRole('button', { name: 'Simulaciones', exact: true }).click()
    const runResponse = page.waitForResponse(r => r.url().includes('/simulations/') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Generar escenarios', exact: true }).click()
    const first = await (await runResponse).json()
    assert.equal(first.status, 'available')
    assert.equal(first.paths, 2000)
    assert.equal(first.observations, 1254)
    assert.equal(first.is_demo, false)
    await page.locator('.scenario-table tbody tr').first().waitFor()
    assert.equal(await page.locator('.scenario-table tbody tr').count(), 3)
    for (let i = 0; i < 13; i++) {
      assert(first.scenarios.pessimistic[i].price <= first.scenarios.base[i].price)
      assert(first.scenarios.base[i].price <= first.scenarios.optimistic[i].price)
    }
    let requests = 0
    const count = request => { if (request.url().includes('/simulations/') && request.method() === 'POST') requests++ }
    page.on('request', count)
    await page.getByLabel('Optimista · percentil 90', { exact: true }).uncheck()
    await page.waitForTimeout(250)
    assert.equal(requests, 0)
    page.off('request', count)
    await page.getByLabel('Optimista · percentil 90', { exact: true }).check()
    steps.push('Tres percentiles de la misma ejecución y leyenda sin nueva solicitud')
    await page.locator('.simulation-settings > summary').click()
    await page.getByLabel('Tasa anual del modelo', { exact: true }).fill('0')
    await page.getByLabel('Volatilidad anual', { exact: true }).fill('0')
    const changedResponse = page.waitForResponse(r => r.url().includes('/simulations/') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Generar escenarios', exact: true }).click()
    const changed = await (await changedResponse).json()
    assert.equal(new Set(changed.scenarios.base.map(point => point.price)).size, 1)
    const restoredResponse = page.waitForResponse(r => r.url().includes('/simulations/') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Restablecer supuestos históricos', exact: true }).click()
    assert.deepEqual((await (await restoredResponse).json()).scenarios, first.scenarios)
    steps.push('Controles y restablecimiento reproducible; volatilidad y tasa cero producen precio constante')
    await page.locator('.simulation-panel').screenshot({ path: path.join(output, 'simulacion_escritorio.png') })
    console.log('Simulaciones verificadas; comprobando IA real...')
    await page.getByRole('button', { name: 'Explicación de IA', exact: true }).click()
    const analysisResponse = page.waitForResponse(r => r.url().includes('/analysis/') && r.request().method() === 'GET', { timeout: 180000 })
    await page.getByRole('button', { name: 'Generar explicación de IA', exact: true }).click()
    const analysisHttp = await analysisResponse
    const analysis = await analysisHttp.json()
    assert.equal(analysisHttp.status(), 200, JSON.stringify(analysis))
    assert.equal(analysis.validated, true)
    assert.equal(Object.keys(analysis.analysis.pillars).length, 5)
    await page.getByRole('region', { name: 'Resumen de IA' }).waitFor()
    await page.getByText('Explicación de los cinco pilares', { exact: true }).click()
    await page.getByText('Fuentes y validación del análisis', { exact: true }).click()
    assert(analysis.sources.every(source => source.startsWith('https://')))
    steps.push('Generación real local en lenguaje sencillo, cinco explicaciones y referencias validadas')
    await page.locator('.ai-panel').screenshot({ path: path.join(output, 'ia_sencilla.png') })
    console.log('IA sencilla verificada; comprobando lenguaje técnico...')
    const [technicalHttp] = await Promise.all([
      page.waitForResponse(r => r.url().includes('/analysis/') && r.url().includes('technical'), { timeout: 180000 }),
      page.getByLabel('Nivel de explicación', { exact: true }).selectOption('technical'),
    ])
    const technical = await technicalHttp.json()
    assert.equal(technicalHttp.status(), 200, JSON.stringify(technical))
    assert.equal(technical.level, 'technical')
    assert.deepEqual(technical.metrics, analysis.metrics)
    steps.push('Lenguaje técnico generado sobre las mismas cifras y periodo')
    for (const [name, width, height] of [['escritorio', 1440, 1000], ['movil', 390, 844]]) {
      await page.setViewportSize({ width, height })
      await page.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur() })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      await page.getByRole('button', { name: 'Simulaciones', exact: true }).click()
      await page.locator('.simulation-panel').screenshot({ path: path.join(output, `simulacion_${name}.png`) })
      await page.getByRole('button', { name: 'Explicación de IA', exact: true }).click()
      await page.locator('.ai-panel').screenshot({ path: path.join(output, `ia_${name}.png`) })
      await page.getByRole('button', { name: 'Resumen', exact: true }).click()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
      await page.screenshot({ path: path.join(output, `resumen_${name}.png`), fullPage: true })
    }
    steps.push('Simulación e IA visibles a 1440 y 390 píxeles sin desbordamiento')
    await page.reload()
    await page.getByRole('button', { name: 'Salud financiera', exact: true }).click()
    await page.locator('.overall-score-value').getByText('85,25', { exact: false }).waitFor()
    await page.getByRole('button', { name: 'Explicación de IA', exact: true }).click()
    const cachedResponse = page.waitForResponse(r => r.url().includes('/analysis/'))
    await page.getByRole('button', { name: 'Generar explicación de IA', exact: true }).click()
    const cached = await (await cachedResponse).json()
    assert.equal(cached.cache_hit, true)
    assert.equal(cached.analysis_id, analysis.analysis_id)
    steps.push('Página recargada conserva funciones y recupera el análisis validado desde caché')
    await page.goto(`${web}/company/AAPL`)
    await page.getByRole('button', { name: 'Simulaciones', exact: true }).click()
    await page.getByRole('button', { name: 'Generar escenarios', exact: true }).click()
    await page.getByText(/No se dispone de un histórico válido suficiente/).waitFor()
    await page.getByRole('button', { name: 'Explicación de IA', exact: true }).click()
    await page.getByRole('button', { name: 'Generar explicación de IA', exact: true }).click()
    await page.getByRole('alert').waitFor()
    assert.equal(await page.getByRole('region', { name: 'Resumen de IA' }).count(), 0)
    steps.push('Empresa sin datos no recibe curvas ni análisis heredados de Microsoft')
    assert.deepEqual(errors, [])
    const report = { recorded_at: new Date().toISOString(), passed: true, browser: 'Google Chrome ' + browser.version(), steps, errors,
      simulation: { id: first.simulation_id, model: first.model_version, observations: first.observations, paths: first.paths, source_hash: first.source_sha256 },
      ai: { model: analysis.model, provider: analysis.provider, version: analysis.schema_version, simple_id: analysis.analysis_id,
        technical_id: technical.analysis_id, validated: true, sources: analysis.sources, is_real_provider: true,
        simple: analysis.analysis, technical: technical.analysis } }
    fs.writeFileSync(path.join(output, 'resultado.json'), JSON.stringify(report, null, 2))
    console.log(JSON.stringify(report))
  } finally { await browser.close() }
})().catch(error => { console.error(error.stack); process.exitCode = 1 })
