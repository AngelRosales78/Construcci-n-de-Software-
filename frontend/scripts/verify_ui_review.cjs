const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { chromium } = require('playwright')
const root = path.resolve(__dirname, '../../..')
const output = path.join(root, 'output/ui_correcciones_27_octubre')
const credentials = JSON.parse(fs.readFileSync(path.join(root, 'presentation_runtime_sprint2/demo_credentials.json'), 'utf8'))
const base = 'http://127.0.0.1:55183'
fs.mkdirSync(output, { recursive: true })

;(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const report = { recorded_at: new Date().toISOString(), browser: browser.version(), passed: false, steps: [], sizes: {}, errors: [] }
  page.on('pageerror', error => report.errors.push(error.message))
  page.setDefaultTimeout(20000)
  const shot = async name => page.screenshot({ path: path.join(output, name + '.png'), fullPage: true })
  const size = async () => page.evaluate(() => ({ height: document.documentElement.scrollHeight, overflow: document.documentElement.scrollWidth > innerWidth + 1 }))
  const searchResponse = () => page.waitForResponse(response => response.url().includes('/api/v1/companies/search/'))
  try {
    await page.goto(base + '/login')
    await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
    await page.getByText('Escribe tu nombre de usuario.', { exact: true }).waitFor()
    assert.equal(await page.locator('#username').getAttribute('aria-invalid'), 'true')
    await shot('login_errores_espanol')
    await page.locator('#username').fill(credentials.username)
    await page.locator('#password').fill(credentials.password)
    await page.getByRole('button', { name: 'Mostrar contraseña', exact: true }).click()
    assert.equal(await page.locator('#password').getAttribute('type'), 'text')
    await page.getByRole('button', { name: 'Ocultar contraseña', exact: true }).click()
    await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
    await page.waitForURL('**/dashboard')
    report.steps.push('Errores en español asociados al campo; mostrar/ocultar conserva el inicio de sesión real')

    await page.goto(base + '/search')
    await page.locator('.company-card').first().waitFor()
    await shot('explorador_escritorio')
    const filtered = searchResponse()
    await page.getByRole('checkbox', { name: 'Solo empresas con indicadores cargados' }).check()
    const result = await (await filtered).json()
    assert(result.count >= 1 && result.count < 503)
    assert(result.results.every(company => ['market_cap', 'per', 'roe'].some(key => company[key] !== null)))
    await page.getByRole('combobox', { name: 'Buscar empresas' }).fill('Microsoft')
    await page.waitForURL(url => url.searchParams.get('q') === 'Microsoft')
    await page.getByLabel('Sector:', { exact: true }).selectOption('technology')
    await page.getByLabel('Ordenar por:', { exact: true }).selectOption('market_cap')
    await page.waitForURL(url => url.searchParams.get('ordering') === 'market_cap')
    await page.locator('.company-card').first().waitFor()
    const saved = new URL(page.url()).search
    await page.locator('.company-card').first().click()
    await page.waitForURL('**/company/MSFT')
    await page.getByRole('button', { name: '← Volver', exact: true }).click()
    await page.waitForURL(url => url.pathname === '/search' && url.search === saved)
    assert.equal(await page.getByRole('combobox', { name: 'Buscar empresas' }).inputValue(), 'Microsoft')
    await page.reload()
    await page.locator('.company-card').first().waitFor()
    assert.equal(await page.getByLabel('Sector:', { exact: true }).inputValue(), 'technology')
    assert(await page.getByRole('checkbox', { name: 'Solo empresas con indicadores cargados' }).isChecked())
    report.steps.push('Filtro sobre todo el catálogo, URL persistida, vuelta desde la ficha y recarga sin perder consulta ni filtros')

    const pattern = '**/api/v1/companies/search/**'
    await page.route(pattern, route => route.abort())
    await page.reload()
    await page.getByRole('alert').waitFor()
    assert.equal(await page.getByText('No se encontraron empresas', { exact: true }).count(), 0)
    await shot('error_red_con_reintento')
    await page.unroute(pattern)
    const retried = searchResponse()
    await page.getByRole('button', { name: 'Reintentar', exact: true }).click()
    assert.equal((await retried).status(), 200)
    await page.locator('.company-card').first().waitFor()
    await page.route(pattern, route => route.abort())
    await page.reload()
    await page.getByRole('alert').waitFor()
    await page.unroute(pattern)
    const submitted = searchResponse()
    await page.getByRole('button', { name: 'Buscar', exact: true }).click()
    assert.equal((await submitted).status(), 200)
    await page.locator('.company-card').first().waitFor()
    report.steps.push('Fallo de red simulado sin mensaje vacío contradictorio; Reintentar y Buscar recuperan la misma consulta')

    await page.goto(base + '/company/MSFT')
    await page.getByText('Zona favorable según Altman-Z', { exact: true }).waitFor()
    assert.equal(await page.getByText('Muy sólido', { exact: true }).count(), 0)
    await shot('resumen_escritorio')
    await page.getByRole('button', { name: 'Salud financiera', exact: true }).click()
    await page.getByLabel('Ejercicio fiscal', { exact: true }).selectOption('2023')
    await page.getByText(/Ejercicio: 2023/).waitFor()
    assert.equal(await page.locator('.data-provenance').isVisible(), false)
    await shot('ejercicio_2023_sin_mezclar_balance')
    await page.getByLabel('Ejercicio fiscal', { exact: true }).selectOption('')
    await page.locator('.overall-score-value').getByText('85,25', { exact: false }).waitFor()
    await page.getByRole('button', { name: 'Mostrar Rentabilidad', exact: true }).click()
    assert.equal(await page.locator('.pillar-toggle[aria-expanded="true"]').count(), 1)
    await page.locator('.pillar-radar-notes').getByRole('link', { name: 'Solvencia', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'Mostrar Solvencia' }).getAttribute('aria-expanded'), 'true')
    assert.equal(await page.getByRole('button', { name: 'Mostrar Rentabilidad' }).getAttribute('aria-expanded'), 'false')
    await page.getByRole('button', { name: 'Mostrar Liquidez', exact: true }).click()
    await shot('salud_escritorio')
    report.steps.push('Periodos separados, puntaje conservado, etiquetas académicas y acordeones enlazados desde el radar')

    await page.getByRole('button', { name: 'Simulaciones', exact: true }).click()
    await page.getByRole('button', { name: 'Generar escenarios', exact: true }).click()
    await page.locator('.scenario-table tbody tr').first().waitFor()
    assert.equal(await page.locator('.scenario-swatch').count(), 3)
    await page.getByText('Qué significan los escenarios y sus percentiles', { exact: true }).click()
    await shot('simulaciones_con_ayuda')
    await page.getByRole('button', { name: 'Explicación de IA', exact: true }).click()
    await page.getByRole('button', { name: 'Generar explicación de IA', exact: true }).click()
    await page.getByRole('region', { name: 'Resumen de IA' }).waitFor({ timeout: 160000 })
    await page.getByText('Guía para interpretar estos indicadores', { exact: true }).waitFor()
    assert(await page.locator('.analysis-key-value strong').first().isVisible())
    await shot('ia_con_cifras_visibles')
    report.steps.push('Simulación conectada con leyenda y ayudas; IA validada con referencias numéricas visibles')

    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(base + '/search')
    await page.locator('.company-card').first().waitFor()
    report.sizes.explorer = await size()
    assert.equal(report.sizes.explorer.overflow, false)
    assert(report.sizes.explorer.height < 7000)
    await shot('explorador_movil')
    await page.goto(base + '/company/MSFT')
    await page.getByRole('button', { name: 'Resumen', exact: true }).waitFor()
    report.sizes.summary = await size()
    await page.evaluate(() => scrollTo(0, 800))
    const top = await page.locator('.company-sections').evaluate(element => element.getBoundingClientRect().top)
    assert(top >= -1 && top <= 5)
    await page.evaluate(() => scrollTo(0, 0))
    await shot('resumen_movil')
    await page.getByRole('button', { name: 'Salud financiera', exact: true }).click()
    await page.locator('.overall-score-value').waitFor()
    report.sizes.pillars = await size()
    assert.equal(report.sizes.pillars.overflow, false)
    await shot('salud_movil')
    await page.goto(base + '/company/AAPL')
    await page.locator('.empty-financial-notice').waitFor()
    assert.equal(await page.locator('.terminal-financial-grid').count(), 0)
    await shot('empresa_sin_datos_movil')
    report.steps.push('Móvil sin desbordamiento, catálogo compacto, navegación a mano al desplazar y estado vacío único')
    report.passed = true
    assert.deepEqual(report.errors, [])
  } finally {
    fs.writeFileSync(path.join(output, 'resultado.json'), JSON.stringify(report, null, 2))
    await browser.close()
  }
  console.log(JSON.stringify(report))
})().catch(error => { console.error(error.stack); process.exitCode = 1 })
