const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const repo=path.resolve(__dirname,'..')
const {chromium}=require(require.resolve('playwright',{paths:[path.join(repo,'frontend')]}))
const web='http://127.0.0.1:55193',api='http://127.0.0.1:58020/api/v1'
;(async()=>{
 const out=path.resolve(repo,'../output/financial-assistant');fs.mkdirSync(out,{recursive:true})
 const creds=JSON.parse(fs.readFileSync(path.resolve(repo,'../presentation_runtime_sprint3/demo_credentials.json'),'utf8').replace(/^\uFEFF/,'')).pro
 const browser=await chromium.launch({channel:'msedge',headless:true})
 const observations=[],errors=[]
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}})
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto(web+'/login');await page.locator('#username').fill(creds.username);await page.locator('#password').fill(creds.password)
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();await page.waitForURL('**/dashboard')
  const token=await page.evaluate(()=>localStorage.getItem('access_token'))
  const headers={Authorization:'Bearer '+token}
  const ask=async(question,expected,history=[])=>{
   const response=await page.request.post(api+'/companies/MSFT/assistant/',{headers,data:{action:'question',fiscal_year:2024,question,history},timeout:100000})
   const body=await response.json();assert.equal(response.status(),200,JSON.stringify(body))
   if(expected)assert.ok(body.answer.topics.some(topic=>expected.includes(topic)),question+': '+JSON.stringify(body.answer.topics))
   observations.push({question,topics:body.answer.topics,cards:body.answer.cards.map(card=>card.id)})
   process.stdout.write(question+' → '+body.answer.topics.join(', ')+'\n')
   return body
  }
  await page.goto(web+'/company/MSFT?section=analysis&fiscal_year=2024')
  const assistant=page.getByRole('region',{name:'Tu asistente financiero',exact:true})
  await assistant.getByRole('button',{name:'Pedir lectura de IA'}).waitFor()
  await page.evaluate(()=>document.fonts.ready)
  for(const width of [1440,768,390,360]){
   await page.setViewportSize({width,height:1000});await assistant.scrollIntoViewIfNeeded()
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Resumen '+width)
   await page.screenshot({path:path.join(out,`resumen-${width}.png`)})
  }
  await page.setViewportSize({width:1440,height:1000})
  await assistant.getByRole('button',{name:'Preguntar',exact:true}).click()
  const debtResponse=page.waitForResponse(response=>response.url().includes('/companies/MSFT/assistant/') && response.request().method()==='POST',{timeout:100000})
  await assistant.getByRole('button',{name:'¿Cómo están sus deudas?',exact:true}).click()
  const debt=await (await debtResponse).json()
  process.stdout.write('Consulta de deudas → '+debt.answer.topics.join(', ')+'\n')
  await assistant.locator('.assistant-turn').waitFor({timeout:100000})
  assert.ok(await assistant.locator('.assistant-turn .assistant-fact').count())
  await assistant.locator('.assistant-turn').scrollIntoViewIfNeeded();await page.screenshot({path:path.join(out,'pregunta-deudas.png')})
  await assistant.getByLabel('Tu pregunta',{exact:true}).fill('¿Podrías explicarlo más?')
  await assistant.getByRole('button',{name:'Enviar pregunta',exact:true}).click()
  await page.waitForFunction(()=>document.querySelectorAll('.assistant-turn').length===2,{},{timeout:100000})
  assert.ok(await assistant.getByRole('region',{name:'Ejemplos ilustrativos',exact:true}).count())
  for(const width of [390,360]){
   await page.setViewportSize({width,height:1000});await assistant.locator('.assistant-turn').last().scrollIntoViewIfNeeded()
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Conversación '+width)
   await page.screenshot({path:path.join(out,`conversacion-${width}.png`)})
  }
  await page.setViewportSize({width:1440,height:1000})
  await assistant.getByRole('button',{name:'Reiniciar conversación',exact:true}).click()
  assert.equal(await assistant.locator('.assistant-turn').count(),0)
  const liquid=await ask('¿Qué significa su liquidez?',['liquidity','current_ratio','quick_ratio'])
  await ask('¿Y eso qué significa?',['liquidity','current_ratio','quick_ratio'],[{question:'¿Qué significa su liquidez?',topics:liquid.answer.topics}])
  await ask('¿Qué significa su Altman-Z?',['altman'])
  await ask('¿Qué información falta?',['missing'])
  await ask('¿Por qué cambiaron sus beneficios?',['causes'])
  const advice=await ask('¿Debería comprar estas acciones para ganar dinero?',['advice'])
  assert.equal(advice.answer.cards.length,0)
  const other=await ask('¿Y la liquidez de Tesla?',['out_of_scope'])
  assert.equal(other.answer.cards.length,0)
  await assistant.getByRole('button',{name:'Cambios entre años',exact:true}).click()
  await assistant.getByLabel('Ejercicio anterior',{exact:true}).selectOption('2023')
  await assistant.getByRole('button',{name:'Ver cambios',exact:true}).click()
  await assistant.locator('.assistant-change-table tbody tr').first().waitFor()
  assert.ok(await assistant.getByText(/Aumentó|Disminuyó|Sin cambio/).count())
  await assistant.locator('.assistant-change-table').scrollIntoViewIfNeeded();await page.screenshot({path:path.join(out,'cambios-verificados.png')})
  await assistant.getByRole('button',{name:'Aprender',exact:true}).click()
  await assistant.getByRole('button',{name:'Entender la liquidez',exact:true}).click()
  await assistant.getByRole('radio',{name:'No, puede incluir inventario y cuentas por cobrar.',exact:true}).check()
  await assistant.getByRole('button',{name:'Comprobar mi respuesta',exact:true}).click()
  await assistant.locator('.assistant-feedback').waitFor()
  assert.match(await assistant.locator('.assistant-feedback').innerText(),/Correcto/)
  await page.screenshot({path:path.join(out,'tutor.png')})
  await page.goto(web+'/company/AAPL?section=analysis&fiscal_year=2025')
  await page.getByRole('button',{name:'Cambios entre años',exact:true}).click()
  await page.getByLabel('Ejercicio anterior',{exact:true}).selectOption('2024')
  await page.getByRole('button',{name:'Ver cambios',exact:true}).click()
  await page.locator('.assistant-change-table').waitFor()
  assert.match(await page.locator('.financial-assistant .assistant-period-note').innerText(),/normalizadas/)
  assert.equal(await page.locator('.assistant-change-table tbody tr td:nth-child(2)').evaluateAll(cells=>cells.every(cell=>cell.textContent==='No comparable')),true)
  await page.goto(web+'/compare?a=GOOGL&b=META&fiscal_year=2024')
  await page.getByRole('button',{name:'Abrir asistente',exact:true}).click()
  const compare=page.getByRole('region',{name:'Entiende la comparación',exact:true})
  await compare.getByRole('button',{name:'Pedir lectura de IA',exact:true}).waitFor()
  await compare.getByRole('button',{name:'Pedir lectura de IA',exact:true}).click()
  await compare.locator('.assistant-answer').waitFor({timeout:100000})
  assert.ok(await compare.locator('.assistant-answer .assistant-fact').count())
  for(const width of [1440,390,360]){
   await page.setViewportSize({width,height:1000});await compare.scrollIntoViewIfNeeded()
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Comparación '+width)
   await page.screenshot({path:path.join(out,`comparacion-${width}.png`)})
  }
  assert.deepEqual(errors,[])
  fs.writeFileSync(path.join(out,'resultado.json'),JSON.stringify({verified_at:new Date().toISOString(),observations,errors},null,2))
  process.stdout.write('Recorrido del asistente completado: conversación, cambios, tutor y comparación.\n')
 }finally{await browser.close()}
})().catch(error=>{process.stderr.write(String(error)+'\n');process.exitCode=1})
