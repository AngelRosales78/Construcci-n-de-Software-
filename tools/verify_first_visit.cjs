const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const repo=path.resolve(__dirname,'..')
const {chromium}=require(require.resolve('playwright',{paths:[path.join(repo,'frontend')]}))
const web='http://127.0.0.1:55193'
;(async()=>{
 const out=path.resolve(repo,'../output/first-visit');fs.mkdirSync(out,{recursive:true})
 const creds=JSON.parse(fs.readFileSync(path.resolve(repo,'../presentation_runtime_sprint3/demo_credentials.json'),'utf8').replace(/^\uFEFF/,'')).pro
 const browser=await chromium.launch({channel:'msedge',headless:true})
 const errors=[],checks=[],zones=[]
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}})
  page.on('pageerror',error=>errors.push(error.message))
  const noOverflow=async label=>assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,label)
  const capture=async name=>page.screenshot({path:path.join(out,name+'.png'),animations:'disabled'})
  await page.goto(web+'/login');await page.locator('#username').fill(creds.username);await page.locator('#password').fill(creds.password)
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();await page.waitForURL('**/dashboard')
  await page.evaluate(()=>document.fonts.ready)
  assert.match(await page.locator('body').evaluate(el=>getComputedStyle(el).fontFamily),/Source Sans 3/)
  await page.locator('.hero-company-image img').evaluate(img=>img.decode())
  for(const width of [1440,768,390,360]){
   await page.setViewportSize({width,height:844});await page.evaluate(()=>scrollTo(0,0));await noOverflow('Inicio '+width);await capture('inicio-'+width)
   const search=await page.getByRole('button',{name:'Explorar empresas',exact:false}).boundingBox()
   assert.ok(search.y+search.height<=844,'Búsqueda visible '+width)
  }
  await page.setViewportSize({width:1440,height:1000})
  await page.getByRole('button',{name:'Soy nuevo, ¿cómo empiezo?',exact:true}).click()
  assert.equal(await page.locator('#home-start-guide').isVisible(),true)
  assert.equal(await page.locator('#home-start-guide li').count(),3)
  await page.getByRole('button',{name:'Cerrar recorrido',exact:true}).click()
  await page.getByLabel('¿Qué empresa quieres conocer?',{exact:true}).fill('AAPL')
  await page.getByRole('button',{name:'Explorar empresas',exact:false}).click()
  await page.waitForURL('**/search?q=AAPL');await page.getByRole('button',{name:'Ver ficha de Apple Inc.',exact:true}).waitFor()
  checks.push('La primera pantalla explica la acción y permite buscar directamente; guía opcional de tres pasos.')
  for(const ticker of ['AAPL','ADP','AES','JPM']){
   const response=page.waitForResponse(response=>response.url().includes(`/companies/${ticker}/summary/`) && response.status()===200)
   await page.goto(web+'/company/'+ticker)
   const company=await(await response).json()
   const reading=page.locator('#company-overview .financial-health')
   await reading.waitFor();await page.evaluate(()=>document.fonts.ready)
   assert.equal(await reading.getAttribute('data-zone'),company.altman_z.zone==='unknown' ? 'unknown' : company.altman_z.zone)
   if(company.altman_z.score!=null)assert.equal(Number(await reading.locator('.altman-score').innerText()),company.altman_z.score)
   else assert.equal(await reading.locator('.altman-score').count(),0)
   const color=await reading.locator(':scope > strong').evaluate(el=>getComputedStyle(el).color)
   zones.push({ticker,zone:company.altman_z.zone,color,score:company.altman_z.score})
   for(const width of [1440,390,360]){
    await page.setViewportSize({width,height:844});await page.evaluate(()=>scrollTo(0,0));await noOverflow(ticker+' '+width)
    const result=await reading.locator(':scope > strong').boundingBox()
    assert.ok(result.y+result.height<=844,'Zona visible sin buscar el puntaje: '+ticker+' '+width)
    await capture(ticker+'-'+width)
   }
   if(company.altman_z.score!=null){
    assert.equal(await reading.locator('.altman-zone[aria-current]').count(),1)
    assert.ok((await reading.locator(':scope > strong').boundingBox()).y<(await reading.locator('.altman-score').boundingBox()).y)
   }
  }
  assert.equal(new Set(zones.map(row=>row.color)).size,4,JSON.stringify(zones))
  checks.push('Tres zonas y un estado sin datos: nombre, símbolo y colores distintos; clasificación antes que puntaje, visible en celular.')
  await page.setViewportSize({width:1440,height:1000});await page.goto(web+'/company/AAPL')
  const explain=page.getByRole('button',{name:'Explícame este resultado',exact:false})
  await explain.waitFor();await explain.focus()
  let calls=0
  page.on('request',request=>{if(request.method()==='POST' && request.url().includes('/companies/AAPL/assistant/'))calls++})
  await page.keyboard.press('Enter')
  const drawer=page.getByRole('dialog',{name:'Entiende las cifras con IA',exact:true})
  await drawer.waitFor();await drawer.locator('.assistant-turn').waitFor({timeout:100000})
  assert.equal(calls,1,'Una interacción produce una sola pregunta')
  assert.match(await drawer.locator('.assistant-answer-context').innerText(),/AAPL/)
  assert.ok(await drawer.getByRole('heading',{name:'Puntaje Altman-Z',exact:true}).count())
  await capture('ia-contextual-escritorio')
  await page.keyboard.press('Escape');await drawer.waitFor({state:'hidden'})
  assert.equal(await explain.evaluate(el=>el===document.activeElement),true)
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button',{name:'Abrir asistente IA',exact:true}).click()
  await drawer.waitFor();await noOverflow('Asistente móvil')
  const modalSize=await drawer.boundingBox();assert.ok(modalSize.width<=390)
  await capture('ia-contextual-celular')
  await page.getByRole('button',{name:'Cerrar asistente',exact:true}).click()
  await drawer.waitFor({state:'hidden'})
  assert.equal(await page.locator('.assistant-launcher').isVisible(),false)
  checks.push('IA junto al resultado: una pregunta, contexto correcto, cierre con Escape y retorno del foco. Acceso móvil sin tapar datos.')
  await page.setViewportSize({width:1440,height:1000})
  const per=page.locator('.metric-card').filter({has:page.getByText('Precio / beneficio · PER',{exact:true})})
  await per.getByRole('button',{name:'Explícame esta cifra',exact:false}).click()
  await drawer.locator('.assistant-turn').waitFor({timeout:100000})
  assert.ok(await drawer.getByRole('heading',{name:'Precio / beneficio · PER',exact:true}).count())
  await capture('ia-per')
  await page.getByRole('button',{name:'Cerrar asistente',exact:true}).click();await drawer.waitFor({state:'hidden'})
  await page.goto(web+'/dashboard')
  await page.getByRole('button',{name:/^Asistente IA/}).click()
  await drawer.getByRole('heading',{name:'¿Qué empresa quieres entender?',exact:true}).waitFor()
  const choose=drawer.getByRole('combobox',{name:'Buscar empresa para el asistente',exact:true})
  await choose.fill('MSFT')
  await drawer.getByRole('option',{name:/^MSFT /}).getByRole('button').click()
  await drawer.getByRole('button',{name:'Consultar esta empresa →',exact:true}).click()
  await drawer.getByLabel('Tu pregunta',{exact:true}).waitFor()
  assert.match(await drawer.locator('.assistant-drawer-header p').innerText(),/MSFT/)
  await capture('ia-desde-inicio')
  await page.keyboard.press('Escape');await drawer.waitFor({state:'hidden'})
  checks.push('Ayuda en PER con su referencia propia y selección de empresa desde el inicio.')
  await page.goto(web+'/notifications');await page.getByRole('heading',{name:'Alertas de tus empresas',exact:true}).waitFor()
  assert.ok(await page.getByText('Son cambios de Altman-Z, no avisos de subida o bajada del precio.',{exact:true}).count())
  for(const width of [1440,390,360]){await page.setViewportSize({width,height:1000});await page.evaluate(()=>scrollTo(0,0));await noOverflow('Alertas '+width);await capture('alertas-'+width)}
  await page.emulateMedia({reducedMotion:'reduce'});await page.goto(web+'/company/IBM')
  await page.locator('.altman-outcome-symbol').first().waitFor()
  assert.equal(await page.locator('.altman-outcome-symbol').first().evaluate(el=>getComputedStyle(el).animationName),'none')
  checks.push('Alertas explicadas en tres pasos; sin prometer avisos de precio. Movimiento reducido respetado.')
  assert.deepEqual(errors,[])
  fs.writeFileSync(path.join(out,'resultado.json'),JSON.stringify({verified_at:new Date().toISOString(),checks,zones,errors},null,2))
  checks.forEach(check=>process.stdout.write(check+'\n'))
 }finally{await browser.close()}
})().catch(error=>{process.stderr.write(String(error)+'\n');process.exitCode=1})
