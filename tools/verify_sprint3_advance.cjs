// Recorrido real contra la demo aislada. No publica ni registra credenciales.
const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const repo = path.resolve(__dirname, '..')
const project = path.dirname(repo)
const { chromium } = require(require.resolve('playwright', { paths: [path.join(repo, 'frontend')] }))
const base = 'http://127.0.0.1:55193'
const server = 'http://127.0.0.1:58020/api/v1'
const output = path.join(project, 'output', 'sprint3_advance')
const checks = []

;(async () => {
  const credentials = JSON.parse(fs.readFileSync(path.join(project, 'presentation_runtime_sprint3', 'demo_credentials.json'), 'utf8'))
  fs.mkdirSync(output, { recursive: true })
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage()
    const pageErrors = []
    page.on('pageerror', error => pageErrors.push(error.message))
    const login = async plan => {
      await page.goto(`${base}/login`)
      await page.locator('#username').fill(credentials[plan].username)
      await page.locator('#password').fill(credentials[plan].password)
      await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
      await page.waitForURL('**/dashboard')
    }
    const token = async plan => {
      const response = await context.request.post(`${server}/auth/token/`, { data: credentials[plan] })
      assert.equal(response.status(), 200)
      return (await response.json()).access
    }
    const proToken = await token('pro')
    const freeToken = await token('free')
    const api = async (route, access, options = {}) => context.request.fetch(`${server}${route}`, {
      ...options, headers: { Authorization: `Bearer ${access}` },
    })
    assert.equal((await api('/compare/?a=GOOGL&b=META&fiscal_year=2024', freeToken)).status(), 403)
    checks.push('Free recibe 403 al intentar consultar directamente la API del comparador')
    await login('free')
    await page.goto(`${base}/compare?a=GOOGL&b=META&fiscal_year=2024`)
    await page.getByRole('heading', { name: 'Vista previa · Plan Free' }).waitFor()
    checks.push('Free muestra la vista previa sin resultados Pro')
    await page.screenshot({ path: path.join(output, '01-plan-free.png'), fullPage: true })
    await page.getByRole('button', { name: 'Cerrar Sesión' }).click()
    await page.waitForURL('**/login')
    await login('pro')
    await page.goto(`${base}/search?q=MSFT`)
    const save = page.getByRole('button', { name: 'Guardar MSFT en favoritos', exact: true })
    const alreadySaved = page.getByRole('button', { name: 'MSFT guardado en favoritos', exact: true })
    await page.getByRole('button', { name: /Ver ficha de Microsoft/ }).waitFor()
    if (await save.count()) { await save.click(); await alreadySaved.waitFor() }
    await page.getByRole('link', { name: 'Favoritos', exact: true }).click()
    await page.getByText('Microsoft', { exact: true }).waitFor()
    await page.reload()
    await page.getByText('Microsoft', { exact: true }).waitFor()
    checks.push('Favorito agregado desde la tarjeta, visible en lista y persistente al recargar')
    await page.getByRole('link', { name: 'Ver ficha →' }).first().click()
    await page.getByRole('button', { name: 'MSFT guardado en favoritos', exact: true }).waitFor()
    checks.push('La ficha reconoce el favorito guardado en el servidor')
    await page.getByRole('button', { name: '← Volver', exact: true }).click()
    await page.waitForURL('**/favorites')
    await page.screenshot({ path: path.join(output, '02-favoritos.png'), fullPage: true })
    let response = await api('/favorites/', proToken)
    const before = (await response.json()).results
    response = await api('/favorites/', proToken, { method: 'POST', data: { ticker: 'MSFT' } })
    assert.equal(response.status(), 200)
    response = await api('/favorites/', proToken)
    assert.equal((await response.json()).results.length, before.length)
    response = await api('/favorites/', freeToken)
    assert.deepEqual((await response.json()).results, [])
    checks.push('Repetir POST no duplica favoritos; otra cuenta no puede verlos')
    await page.getByRole('link', { name: 'Comparar', exact: true }).click()
    const choose = async (side, query) => {
      const input = page.getByRole('combobox', { name: `Buscar empresa ${side}` })
      await input.fill(query)
      await page.getByRole('listbox', { name: `Opciones empresa ${side}` }).getByRole('option').first().waitFor()
      await input.press('ArrowDown'); await input.press('Enter')
    }
    await choose('A', 'GOOGL')
    await choose('B', 'GOOGL')
    await page.getByRole('alert').filter({ hasText: 'Elige dos empresas distintas.' }).waitFor()
    await choose('B', 'META')
    await page.getByRole('heading', { name: 'GOOGL y META · FY2024' }).waitFor()
    checks.push('Búsqueda con teclado, rechazo de duplicados y selección GOOGL/META')
    response = await api('/compare/?a=GOOGL&b=META&fiscal_year=2024', proToken)
    assert.equal(response.status(), 200)
    const comparison = await response.json()
    assert.equal(comparison.a.period.start, comparison.b.period.start)
    assert.equal(comparison.a.period.end, comparison.b.period.end)
    assert.ok(comparison.comparisons.some(row => row.status === 'available'))
    assert.equal(comparison.a.ticker, 'GOOGL')
    checks.push('Comparación real conserva identidades, FY2024 y períodos completos coincidentes')
    await page.reload()
    await page.getByRole('heading', { name: 'GOOGL y META · FY2024' }).waitFor()
    await page.getByRole('button', { name: 'Intercambiar A y B' }).click()
    await page.getByRole('heading', { name: 'META y GOOGL · FY2024' }).waitFor()
    checks.push('La URL restaura selección y permite intercambiar A/B')
    await page.screenshot({ path: path.join(output, '03-comparador-escritorio.png'), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: path.join(output, '04-comparador-movil.png'), fullPage: true })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth), false)
    checks.push('Vista móvil 390px sin desbordamiento horizontal de página')
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto(`${base}/compare?a=MSFT&b=META&fiscal_year=2024`)
    await page.getByRole('heading', { name: 'MSFT y META · FY2024' }).waitFor()
    assert.equal(await page.getByRole('cell').filter({ hasText: /^No comparable/ }).count(), 5)
    checks.push('MSFT/META FY2024: fechas distintas, cinco resultados no comparables sin ganador')
    await page.screenshot({ path: path.join(output, '05-periodos-distintos.png'), fullPage: true })
    await page.getByLabel('Ejercicio fiscal de cierre').fill('2010')
    await page.getByRole('heading', { name: 'MSFT y META · FY2010' }).waitFor()
    assert.equal(await page.getByText('Sin balance para este ejercicio', { exact: true }).count(), 2)
    checks.push('Un ejercicio ausente no se reemplaza por el más reciente')
    await page.getByRole('button', { name: 'Quitar empresa B' }).click()
    await page.getByText('Selecciona las dos empresas para continuar.', { exact: false }).waitFor()
    checks.push('Quitar una empresa elimina el resultado anterior')
    assert.deepEqual(pageErrors, [])
    checks.push('Recorrido sin errores JavaScript de página')
    fs.writeFileSync(path.join(output, 'resultado.json'), JSON.stringify({ verified_at: new Date().toISOString(), browser: 'Microsoft Edge headless', checks, page_errors: pageErrors,
      scope: 'Web y API reales. No constituye ejecución en dispositivo Android.' }, null, 2))
    console.log(`${checks.length} comprobaciones de web y API aprobadas. Evidencias: output/sprint3_advance/`)
    await context.close()
  } finally { await browser.close() }
})().catch(error => { console.error(error.stack); process.exitCode = 1 })
