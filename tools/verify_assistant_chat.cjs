const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const repo=path.resolve(__dirname,'..'),out=path.resolve(repo,'../output/assistant-chat')
const {chromium}=require(require.resolve('playwright',{paths:[path.join(repo,'frontend')]}))
const web='http://127.0.0.1:55193',api='http://127.0.0.1:58020/api/v1'
;(async()=>{
 fs.mkdirSync(out,{recursive:true})
 const browser=await chromium.launch({channel:'msedge',headless:true})
 const results=[],errors=[]
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000}})
  page.on('pageerror',error=>errors.push(error.message))
  const creds=JSON.parse(fs.readFileSync(path.resolve(repo,'../presentation_runtime_sprint3/demo_credentials.json'),'utf8').replace(/^\uFEFF/,'')).pro
  await page.goto(web+'/login');await page.locator('#username').fill(creds.username);await page.locator('#password').fill(creds.password)
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();await page.waitForURL('**/dashboard')
  await page.goto(web+'/company/AAPL?section=analysis&fiscal_year=2024')
  const assistant=page.locator('#company-financial .financial-assistant')
  await assistant.getByLabel('Tu pregunta',{exact:true}).waitFor()
  assert.equal(await assistant.getByRole('navigation',{name:'Herramientas del asistente'}).count(),0)
  await page.evaluate(()=>document.fonts.ready)
  const ask=async(question,history=[])=>{
   const started=Date.now()
   const token=await page.evaluate(()=>localStorage.getItem('access_token'))
   const response=await page.request.post(api+'/companies/AAPL/assistant/',{headers:{Authorization:'Bearer '+token},data:{action:'question',fiscal_year:2024,question,history},timeout:60000})
   const body=await response.json()
   results.push({question,status:response.status(),ms:Date.now()-started,generation_mode:body.generation_mode,topics:body.answer?.topics,messages:body.answer?.messages})
   process.stdout.write(JSON.stringify(results.at(-1))+'\n')
   assert.equal(response.status(),200,JSON.stringify(body))
   assert.equal(body.assistant.model,'Qwen/Qwen3.6-35B-A3B-FP8')
   return body
  }
  for(const question of ['hoa','gracias']){
   const answer=await ask(question)
   assert.equal(answer.answer.cards.length,0)
   assert.equal(answer.generation_mode,'conversational_quick_reply')
  }
  const field=assistant.getByLabel('Tu pregunta',{exact:true})
  await field.fill('Hola');await field.press('Enter')
  await assistant.getByRole('log').getByText(/¡Hola!/).waitFor()
  assert.equal(await assistant.getByRole('log').locator('img, .assistant-fact').count(),0)
  await assistant.scrollIntoViewIfNeeded()
  await page.screenshot({path:path.join(out,'01-saludo.png')})
  const liquid=await ask('¿Qué significa su liquidez?')
  assert.equal(liquid.generation_mode,'conversational_ai')
  assert.ok(liquid.answer.messages.length && liquid.answer.evidence_ids.length)
  const followup=await ask('¿Y eso qué significa?',[{question:'¿Qué significa su liquidez?',topics:liquid.answer.topics}])
  assert.deepEqual(followup.answer.topics,liquid.answer.topics)
  const missing=await ask('¿Qué información falta?')
  assert.ok(missing.answer.topics.includes('missing'))
  const ambiguous=await ask('asdfgh zzzz')
  assert.equal(ambiguous.answer.cards.length,0)
  assert.ok(ambiguous.answer.topics.some(topic=>['clarify','out_of_scope'].includes(topic)))
  const outside=await ask('¿Y la liquidez de Tesla?')
  assert.equal(outside.generation_mode,'context_guard');assert.equal(outside.answer.cards.length,0)
  await field.fill('¿Qué significa su Altman-Z?');await assistant.getByRole('button',{name:'Enviar pregunta',exact:true}).click()
  await assistant.getByRole('log').locator('.assistant-turn').nth(1).waitFor({timeout:60000})
  await assistant.getByRole('button',{name:'Enviar pregunta',exact:true}).waitFor({timeout:60000})
  await assistant.locator('.assistant-pending-turn').waitFor({state:'hidden',timeout:60000})
  assert.equal(await assistant.getByRole('alert').count(),0)
  assert.ok(await assistant.getByRole('log').locator('.assistant-turn').nth(1).locator('.assistant-message').count())
  await assistant.scrollIntoViewIfNeeded()
  for(const width of [1440,768,390,360]){
   await page.setViewportSize({width,height:1000})
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'Chat '+width)
   await page.screenshot({path:path.join(out,`02-conversacion-${width}.png`)})
  }
  // Delay only the test response to verify that stopping cannot publish a late turn.
  let release
  const delayed=new Promise(resolve=>{release=resolve})
  await page.route('**/companies/AAPL/assistant/',async route=>{
   if(route.request().method()!=='POST')return route.continue()
   await delayed
   await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(liquid)})
  })
  const count=await assistant.locator('.assistant-turn').count()
  await field.fill('Pregunta para detener');await field.press('Enter')
  await assistant.getByRole('button',{name:'Detener espera',exact:true}).click()
  await assistant.getByText(/Espera detenida/).waitFor({timeout:5000})
  assert.equal(await field.inputValue(),'Pregunta para detener')
  release()
  await page.waitForTimeout(500)
  assert.equal(await assistant.locator('.assistant-turn').count(),count,'No debe publicarse una respuesta después de detener la espera')
  await page.unroute('**/companies/AAPL/assistant/')
  await page.route('**/companies/AAPL/assistant/',route=>route.fulfill({status:503,contentType:'application/json',body:'{"status":"unavailable"}'}))
  await field.fill('Pregunta que se conserva');await field.press('Enter')
  await assistant.getByRole('alert').waitFor()
  assert.equal(await field.inputValue(),'Pregunta que se conserva')
  await page.unroute('**/companies/AAPL/assistant/')
  await assistant.getByRole('button',{name:'Reiniciar conversación'}).click()
  assert.equal(await assistant.locator('.assistant-turn').count(),0)
  await assistant.getByRole('button',{name:'Otras herramientas',exact:true}).click()
  for(const name of ['Lectura rápida','Cambios entre años','Aprender'])assert.equal(await assistant.getByRole('button',{name,exact:true}).count(),1)
  await page.setViewportSize({width:1440,height:1000})
  await page.getByRole('button',{name:'Abrir asistente IA',exact:true}).click()
  const drawer=page.getByRole('dialog',{name:'Entiende las cifras con IA',exact:true})
  const drawerInput=drawer.getByLabel('Tu pregunta',{exact:true})
  await drawerInput.fill('Hola');await drawerInput.press('Enter')
  await drawer.getByRole('log').getByText(/¡Hola!/).waitFor()
  await drawerInput.fill('¿Qué significa su Altman-Z?');await drawerInput.press('Enter')
  await drawer.locator('.assistant-pending-turn').waitFor({state:'hidden',timeout:60000})
  assert.equal(await drawer.getByRole('alert').count(),0)
  for(const [width,height] of [[1440,1000],[768,800],[390,844],[360,640],[320,600]]){
   await page.setViewportSize({width,height})
   await drawer.getByRole('log').evaluate(el=>{el.scrollTop=el.scrollHeight})
   const composer=await drawer.locator('.assistant-question-form').boundingBox()
   assert.ok(composer.y>=0 && composer.y+composer.height<=height,`Composer visible at ${width}x${height}`)
   assert.equal(await drawer.evaluate(el=>el.scrollWidth>el.clientWidth),false,`No horizontal overflow at ${width}`)
   await page.screenshot({path:path.join(out,`03-chat-lateral-${width}.png`),animations:'disabled'})
  }
  await page.emulateMedia({reducedMotion:'reduce'})
  assert.equal(await drawer.evaluate(el=>getComputedStyle(el).animationName),'none')
  await page.keyboard.press('Escape')
  await drawer.waitFor({state:'hidden'})
  assert.deepEqual(errors,[])
  fs.writeFileSync(path.join(out,'resultado.json'),JSON.stringify({verified_at:new Date().toISOString(),results,errors,stop_and_retry_verified:true},null,2))
 }finally{await browser.close()}
})().catch(error=>{process.stderr.write(String(error.stack || error)+'\n');process.exitCode=1})
