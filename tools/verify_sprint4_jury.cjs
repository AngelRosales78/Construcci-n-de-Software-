const fs=require('node:fs')
const path=require('node:path')
const assert=require('node:assert/strict')
const repo=path.resolve(__dirname,'..')
const {chromium}=require(require.resolve('playwright',{paths:[path.join(repo,'frontend')]}))
const state=path.resolve(repo,'../presentation_runtime_sprint3')
const output=path.resolve(repo,'../output/sprint4_jury')
const web='http://127.0.0.1:55193'
const base='http://127.0.0.1:58020/api/v1'

;(async()=>{
  fs.mkdirSync(output,{recursive:true})
  const accounts=JSON.parse(fs.readFileSync(path.join(state,'demo_credentials.json'),'utf8').replace(/^\uFEFF/,''))
  accounts.admin=JSON.parse(fs.readFileSync(path.join(state,'sprint4_admin_credentials.json'),'utf8').replace(/^\uFEFF/,''))
  const browser=await chromium.launch({channel:'msedge',headless:true})
  const checks=[],pageErrors=[]
  try{
    const context=await browser.newContext({viewport:{width:1440,height:1000}})
    const page=await context.newPage()
    page.on('pageerror',error=>pageErrors.push(error.message))
    async function login(role){
      await page.goto(web+'/login')
      await page.locator('#username').fill(accounts[role].username)
      await page.locator('#password').fill(accounts[role].password)
      await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click()
      await page.waitForURL(/\/(dashboard|admin-panel)$/,{timeout:30000})
    }
    async function leave(){await page.getByRole('button',{name:'Cerrar Sesión',exact:true}).click();await page.waitForURL('**/login')}
    async function capture(name){
      await page.screenshot({path:path.join(output,name+'.png'),fullPage:true})
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth),false,'La página no debe desbordarse: '+name)
    }
    await login('pro')
    await page.goto(web+'/dashboard');await page.getByRole('button',{name:/Buscar empresas y consultar fichas/}).waitFor()
    await capture('01-inicio-escritorio')
    await page.goto(web+'/search?q=MSFT');await page.getByRole('button',{name:/Ver ficha de Microsoft/}).waitFor()
    assert.doesNotMatch(await page.locator('body').innerText(),/demostraci[oó]n|\bprueba\b|fictici/i)
    await capture('02-empresas-escritorio')
    checks.push('Acceso Pro, inicio y búsqueda real sin textos internos de demostración')
    await page.goto(web+'/compare?a=GOOGL&b=META&fiscal_year=2024')
    await page.getByRole('heading',{name:'GOOGL y META · FY2024'}).waitFor()
    await capture('03-comparador-escritorio')
    await page.setViewportSize({width:390,height:844});await capture('04-comparador-movil')
    await page.getByRole('button',{name:'Abrir navegación'}).click()
    await page.getByRole('link',{name:'Favoritos',exact:true}).click();await page.waitForURL('**/favorites')
    await page.getByRole('heading',{name:'Mis favoritos'}).waitFor();await capture('05-favoritos-movil')
    checks.push('Comparador Pro y navegación móvil por menú accesible, sin desbordamiento')
    await page.setViewportSize({width:1440,height:1000})
    await page.goto(web+'/profile/subscription');await page.getByRole('heading',{name:'Mi suscripción',exact:true}).waitFor()
    assert.doesNotMatch(await page.locator('body').innerText(),/demostraci[oó]n|\bprueba\b|fictici/i)
    await capture('06-suscripcion')
    await leave();await login('free')
    await page.goto(web+'/compare?a=GOOGL&b=META&fiscal_year=2024')
    await page.getByRole('heading',{name:'Vista previa · Plan Free'}).waitFor()
    await capture('07-plan-free');checks.push('Free mantiene vista previa y no muestra resultados protegidos')
    await leave();await login('admin')
    await page.goto(web+'/admin-panel/users');await page.getByRole('heading',{name:/usuarios/i}).waitFor()
    await page.locator('.account-table tbody tr').first().waitFor();await capture('08-administracion-usuarios')
    await page.goto(web+'/admin-panel/companies?q=MSFT');await page.getByRole('button',{name:'Editar MSFT'}).waitFor()
    await capture('09-administracion-catalogo')
    await page.goto(web+'/admin-panel/monitoring')
    await page.getByRole('heading',{name:'Uso y operación'}).waitFor();await page.getByText('Coste estimado',{exact:true}).waitFor()
    await capture('10-monitoreo-ia')
    for(const [label,name,expected] of [['Planes','11-planes','Cuentas registradas'],['Presupuestos','12-presupuestos','Motor de análisis local'],['Suscripciones','13-suscripciones','Planes incluidos'],['Registros','14-registros','Registros']]){
      const response=page.waitForResponse(response=>response.url().includes('/admin/monitoring/')&&response.status()===200)
      await page.getByRole('button',{name:label,exact:true}).click()
      await response
      if(expected!=='Registros')await page.getByText(expected,{exact:true}).waitFor()
      await capture(name)
    }
    checks.push('Administración real de usuarios, catálogo y las cinco secciones del monitoreo')
    await page.goto(web+'/notifications');await page.getByRole('heading',{name:/avisos/i}).waitFor();await capture('15-avisos')
    await page.goto(web+'/profile/notifications');await page.getByRole('heading',{name:'Preferencias de avisos'}).waitFor()
    await page.getByRole('checkbox',{name:'Correo de alertas'}).waitFor()
    const emailAvailable=await page.getByRole('checkbox',{name:'Correo de alertas'}).isEnabled()
    await capture('16-preferencias');checks.push('Preferencias persistidas; correo disponible: '+emailAvailable)
    await page.goto(web+'/profile');await page.getByRole('button',{name:'Guardar perfil'}).waitFor();await capture('17-perfil')
    await page.setViewportSize({width:390,height:844})
    await page.goto(web+'/admin-panel/monitoring');await page.getByText('Coste estimado',{exact:true}).waitFor();await capture('18-monitoreo-movil')
    assert.deepEqual(pageErrors,[])
    fs.writeFileSync(path.join(output,'resultado.json'),JSON.stringify({verified_at:new Date().toISOString(),checks,page_errors:pageErrors},null,2))
    console.log(checks.join('\n'))
    await context.close()
  }finally{await browser.close()}
})().catch(error=>{console.error(error.stack);process.exitCode=1})
