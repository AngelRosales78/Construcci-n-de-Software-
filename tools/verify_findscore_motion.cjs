const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict')
const repo=path.resolve(__dirname,'..'),before=process.argv.includes('--before')
const out=path.resolve(repo,'../output/findscore-motion',before?'before':'after')
const {chromium}=require(require.resolve('playwright',{paths:[path.join(repo,'frontend')]}))
const web='http://127.0.0.1:55193'
;(async()=>{
  fs.mkdirSync(out,{recursive:true})
  const browser=await chromium.launch({channel:'msedge',headless:true})
  let context
  const errors=[],checks=[]
  try{
    const login=await browser.newContext()
    const access=await login.newPage()
    const account=JSON.parse(fs.readFileSync(path.resolve(repo,'../presentation_runtime_sprint3/demo_credentials.json'),'utf8').replace(/^\uFEFF/,'')).pro
    await access.goto(web+'/login')
    await access.locator('#username').fill(account.username)
    await access.locator('#password').fill(account.password)
    await access.getByRole('button',{name:'Iniciar sesión',exact:true}).click()
    await access.waitForURL('**/dashboard')
    const state=await login.storageState()
    await login.close()
    context=await browser.newContext({storageState:state,viewport:{width:1440,height:1000},reducedMotion:'no-preference',...(!before?{recordVideo:{dir:out,size:{width:1440,height:1000}}}:{})})
    const page=await context.newPage()
    page.on('pageerror',error=>errors.push(error.message))
    const pause=()=>page.waitForTimeout(before?100:900)
    const capture=async(name)=>{
      await page.evaluate(()=>document.fonts.ready)
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,name)
      await page.screenshot({path:path.join(out,name+'.png')})
    }
    await page.goto(web+'/dashboard')
    await page.locator('.hero-company-image img').evaluate(img=>img.decode())
    await page.mouse.move(700,85)
    await pause()
    await capture('01-inicio')
    const button=page.locator('.hero-search .primary-action')
    await button.hover()
    await page.waitForTimeout(400)
    if(!before)assert.ok(await button.evaluate(el=>new DOMMatrix(getComputedStyle(el).transform).m42<=-1.5),'Respuesta del botón al cursor')
    await capture('02-boton-hover');await pause()
    await page.locator('.hero-company-image').hover()
    await page.waitForTimeout(750)
    if(!before)assert.ok(await page.locator('.hero-company-image img').evaluate(el=>new DOMMatrix(getComputedStyle(el).transform).a>1.02),'Acercamiento de la imagen')
    await pause()
    const sector=page.locator('.sector-tile').first()
    await sector.scrollIntoViewIfNeeded();await pause();await sector.hover()
    await page.waitForTimeout(400);await capture('03-sector-hover');await pause()
    await page.goto(web+'/search')
    const card=page.locator('.company-card-wrapper').first()
    await card.locator('.favorite-button:not(:disabled)').waitFor()
    await card.scrollIntoViewIfNeeded();await pause()
    await card.locator('.company-card').hover();await page.waitForTimeout(450)
    if(!before)assert.ok(await card.evaluate(el=>new DOMMatrix(getComputedStyle(el).transform).m42<=-3.5),'La tarjeta completa responde al cursor')
    await capture('04-empresa-hover');await pause()
    const dimensions=await card.boundingBox()
    await page.mouse.move(210,85);await page.waitForTimeout(400)
    if(!before)assert.ok(Math.abs((await card.boundingBox()).y-dimensions.y-4)<1,'El movimiento no cambia la distribución')
    await card.locator('.favorite-button').hover();await pause()
    await page.goto(web+'/company/AAPL?fiscal_year=2024')
    await page.locator('#company-overview .financial-health').waitFor()
    await pause();await capture('05-ficha')
    const opener=page.getByRole('button',{name:'Abrir asistente IA',exact:true})
    await opener.scrollIntoViewIfNeeded();await opener.hover();await pause();await opener.click()
    const drawer=page.getByRole('dialog',{name:'Entiende las cifras con IA',exact:true})
    await drawer.waitFor();await page.waitForTimeout(550);await capture('06-asistente');await pause()
    await page.keyboard.press('Escape');await drawer.waitFor({state:'hidden'})
    assert.equal(await opener.evaluate(el=>el===document.activeElement),true)
    checks.push('Inicio, botones, imagen, sectores, tarjetas y asistente; Escape devuelve el foco.')
    if(!before){
      await page.emulateMedia({reducedMotion:'reduce'})
      await page.goto(web+'/search');await card.waitFor();await card.locator('.company-card').hover()
      assert.equal(await card.evaluate(el=>getComputedStyle(el).transform),'none')
      assert.equal(await card.evaluate(el=>getComputedStyle(el).transitionDuration),'0s')
      checks.push('Movimiento reducido elimina desplazamientos, animaciones y transiciones.')
      const touch=await browser.newContext({storageState:state,viewport:{width:390,height:1000},isMobile:true,hasTouch:true})
      const phone=await touch.newPage()
      for(const url of ['/dashboard','/search','/company/AAPL']){
        await phone.goto(web+url)
        await phone.locator(url==='/search'?'.company-card':url==='/dashboard'?'.hero-search':'.financial-health').first().waitFor()
        assert.equal(await phone.evaluate(()=>matchMedia('(hover:hover) and (pointer:fine)').matches),false)
        assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
        await phone.screenshot({path:path.join(out,'movil-'+url.split('/').pop()+'.png')})
      }
      await touch.close();checks.push('En teléfono no se activan los efectos exclusivos del ratón; no hay desbordamiento.')
    }
    assert.deepEqual(errors,[])
    const video=page.video()
    await context.close();context=null
    if(video)fs.renameSync(await video.path(),path.join(out,'FINDSCORE-animaciones.webm'))
    fs.writeFileSync(path.join(out,'resultado.json'),JSON.stringify({verified_at:new Date().toISOString(),checks,page_errors:errors},null,2))
    process.stdout.write(JSON.stringify({before,checks,page_errors:errors})+'\n')
  }finally{if(context)await context.close();await browser.close()}
})().catch(error=>{process.stderr.write(String(error)+'\n');process.exitCode=1})
